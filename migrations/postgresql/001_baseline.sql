-- PostgreSQL baseline for a NEW, EMPTY Crew Center database.
-- Do not apply historical MySQL migrations to this database.
-- Explicit IDs may be imported; run 002_reset_identity_sequences.sql afterward.
BEGIN;
SET LOCAL TIME ZONE 'UTC';

CREATE TABLE ranks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  timereq INTEGER NOT NULL,
  imageurl TEXT,
  barcount SMALLINT NOT NULL DEFAULT 1 CHECK (barcount BETWEEN 0 AND 255),
  bartone VARCHAR(10) NOT NULL DEFAULT 'gold',
  starcount SMALLINT NOT NULL DEFAULT 0 CHECK (starcount BETWEEN 0 AND 255)
);

CREATE TABLE awards (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  name_zh VARCHAR(255),
  description TEXT NOT NULL,
  description_zh TEXT,
  imageurl TEXT NOT NULL,
  featured SMALLINT,
  category VARCHAR(50) NOT NULL DEFAULT 'milestone',
  criteria JSON,
  CONSTRAINT awards_one_featured UNIQUE (featured)
);

CREATE TABLE pilots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  callsign VARCHAR(120) NOT NULL,
  name TEXT NOT NULL,
  ifc TEXT NOT NULL,
  ifuserid VARCHAR(36),
  email TEXT NOT NULL,
  password TEXT NOT NULL,
  transhours INTEGER NOT NULL DEFAULT 0,
  transflights INTEGER NOT NULL DEFAULT 0,
  violand DOUBLE PRECISION,
  grade INTEGER,
  notes VARCHAR(1200) NOT NULL DEFAULT '',
  status INTEGER NOT NULL DEFAULT 0,
  joined TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE aircraft (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  ifaircraftid TEXT,
  liveryname TEXT,
  ifliveryid TEXT,
  notes VARCHAR(12),
  rankreq INTEGER REFERENCES ranks(id),
  awardreq INTEGER REFERENCES awards(id),
  status INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE awards_granted (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  awardid INTEGER NOT NULL REFERENCES awards(id),
  pilotid INTEGER NOT NULL REFERENCES pilots(id),
  dateawarded DATE NOT NULL,
  CONSTRAINT awards_granted_pilot_award UNIQUE (pilotid, awardid)
);

CREATE TABLE multipliers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code INTEGER NOT NULL,
  multiplier DOUBLE PRECISION NOT NULL,
  name VARCHAR(120) NOT NULL,
  minrankid INTEGER
);

CREATE TABLE notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pilotid INTEGER NOT NULL REFERENCES pilots(id),
  icon VARCHAR(20) NOT NULL,
  subject VARCHAR(20) NOT NULL,
  content VARCHAR(60) NOT NULL,
  datetime TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  read_at TIMESTAMPTZ
);
CREATE INDEX notifications_pilot_unread ON notifications (pilotid, read_at);

CREATE TABLE options (
  name VARCHAR(120) PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE permissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  userid INTEGER NOT NULL REFERENCES pilots(id)
);

CREATE TABLE pireps (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flightnum TEXT,
  departure VARCHAR(4) NOT NULL,
  arrival VARCHAR(4) NOT NULL,
  flighttime INTEGER NOT NULL,
  pilotid INTEGER NOT NULL REFERENCES pilots(id),
  date DATE NOT NULL,
  aircraftid INTEGER NOT NULL REFERENCES aircraft(id),
  fuelused INTEGER NOT NULL,
  multi TEXT NOT NULL,
  status INTEGER DEFAULT 0
);

CREATE TABLE pireps_comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pirepid INTEGER NOT NULL REFERENCES pireps(id),
  userid INTEGER NOT NULL REFERENCES pilots(id),
  content TEXT NOT NULL,
  dateposted TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE routes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fltnum TEXT,
  dep VARCHAR(4) NOT NULL,
  arr VARCHAR(4) NOT NULL,
  duration INTEGER NOT NULL,
  notes TEXT
);

CREATE TABLE route_aircraft (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  routeid INTEGER NOT NULL REFERENCES routes(id),
  aircraftid INTEGER NOT NULL REFERENCES aircraft(id)
);

-- The News model has no definition in the legacy base SQL.
CREATE TABLE news (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject TEXT NOT NULL,
  content TEXT NOT NULL,
  author TEXT,
  dateposted TIMESTAMPTZ,
  status INTEGER
);

CREATE TABLE applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pilotid INTEGER NOT NULL REFERENCES pilots(id),
  exam_status SMALLINT NOT NULL DEFAULT 0,
  exam_score DECIMAL(5,2),
  exam_completed_at TIMESTAMPTZ,
  exam_result_received_at TIMESTAMPTZ,
  flight_replay_url TEXT,
  flight_replay_submitted_at TIMESTAMPTZ,
  discord_invite_url TEXT,
  discord_invite_sent_at TIMESTAMPTZ,
  if_grade INTEGER,
  if_violations INTEGER,
  if_metrics_updated_at TIMESTAMPTZ,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT applications_pilotid_unique UNIQUE (pilotid)
);

-- PostgreSQL folds unquoted identifiers. Preserve the auth model's camelCase.
CREATE TABLE tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "pilotId" INTEGER NOT NULL REFERENCES pilots(id) ON DELETE CASCADE,
  token VARCHAR(255) NOT NULL UNIQUE,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "isRevoked" BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_tokens_pilot_id ON tokens ("pilotId");

CREATE TABLE otps (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL,
  otp VARCHAR(255) NOT NULL,
  expires TIMESTAMPTZ NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL,
  "updatedAt" TIMESTAMPTZ NOT NULL
);
CREATE INDEX otps_email ON otps (email);

CREATE TABLE api_cache (
  cache_key VARCHAR(255) PRIMARY KEY,
  value TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX idx_api_cache_expires_at ON api_cache (expires_at);

CREATE TABLE live_aircraft (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration VARCHAR(24) NOT NULL,
  aircraft_id INTEGER NOT NULL REFERENCES aircraft(id),
  current_airport CHAR(4),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  location_updated_by INTEGER REFERENCES pilots(id),
  location_updated_at TIMESTAMPTZ(3),
  if_aircraft_id CHAR(36),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT live_aircraft_registration UNIQUE (registration),
  CONSTRAINT live_aircraft_if_binding UNIQUE (if_aircraft_id)
);

CREATE TABLE live_flights (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id CHAR(36) NOT NULL,
  live_aircraft_id INTEGER NOT NULL REFERENCES live_aircraft(id),
  captain_id INTEGER NOT NULL REFERENCES pilots(id),
  callsign VARCHAR(32),
  flight_type VARCHAR(32) NOT NULL DEFAULT 'commercial',
  departure CHAR(4) NOT NULL,
  arrival CHAR(4) NOT NULL,
  queue_order INTEGER,
  scheduled_departure TIMESTAMPTZ(3),
  scheduled_arrival TIMESTAMPTZ(3),
  status VARCHAR(24) NOT NULL DEFAULT 'pending',
  notes TEXT,
  reviewed_by INTEGER REFERENCES pilots(id),
  reviewed_at TIMESTAMPTZ(3),
  review_reason VARCHAR(500),
  actual_departure_at TIMESTAMPTZ(3),
  actual_arrival_at TIMESTAMPTZ(3),
  actual_arrival CHAR(4),
  revision INTEGER NOT NULL DEFAULT 1,
  published_revision INTEGER NOT NULL DEFAULT 0,
  publishing_state VARCHAR(24) NOT NULL DEFAULT 'local',
  if_schedule_id CHAR(36),
  error VARCHAR(500),
  last_published_payload JSON,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT live_flights_public_id UNIQUE (public_id),
  CONSTRAINT live_flights_queue_order UNIQUE (live_aircraft_id, queue_order),
  CONSTRAINT live_flights_time_pair CHECK (
    (scheduled_departure IS NULL AND scheduled_arrival IS NULL)
    OR (scheduled_departure IS NOT NULL AND scheduled_arrival IS NOT NULL
      AND scheduled_arrival > scheduled_departure)
  ),
  CONSTRAINT live_flights_positive_queue_order CHECK (queue_order IS NULL OR queue_order > 0),
  CONSTRAINT live_flights_reserved_queue_order CHECK (status NOT IN ('approved', 'in_progress') OR queue_order IS NOT NULL),
  CONSTRAINT live_flights_flight_type CHECK (flight_type IN ('commercial', 'freight', 'ferry', 'charter', 'training', 'test_flight', 'medical_emergency', 'military', 'vip_executive', 'humanitarian_relief', 'general_aviation', 'airshow', 'other'))
);
COMMENT ON COLUMN live_flights.last_published_payload IS 'Application-authored outgoing payload only; never an IF response';
CREATE INDEX live_flights_queue ON live_flights (live_aircraft_id, status, queue_order);
CREATE INDEX live_flights_captain ON live_flights (captain_id, status, scheduled_departure);
CREATE INDEX live_flights_review ON live_flights (status, created_at);

CREATE TABLE live_flight_members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id INTEGER NOT NULL REFERENCES live_flights(id),
  pilot_id INTEGER NOT NULL REFERENCES pilots(id),
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  reviewed_by INTEGER REFERENCES pilots(id),
  reviewed_at TIMESTAMPTZ(3),
  review_reason VARCHAR(500),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT live_flight_members_pilot UNIQUE (flight_id, pilot_id)
);
CREATE INDEX live_flight_members_assignments ON live_flight_members (pilot_id, status);

CREATE TABLE live_schedule_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  live_aircraft_id INTEGER NOT NULL REFERENCES live_aircraft(id),
  flight_id INTEGER REFERENCES live_flights(id),
  actor_id INTEGER REFERENCES pilots(id),
  action VARCHAR(40) NOT NULL,
  details JSON,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX live_schedule_events_flight ON live_schedule_events (flight_id, created_at);

CREATE TABLE if_live_connections (
  id INTEGER PRIMARY KEY,
  connected_by INTEGER NOT NULL REFERENCES pilots(id),
  organization_id CHAR(36),
  access_token_encrypted TEXT,
  refresh_token_encrypted TEXT,
  expires_at TIMESTAMPTZ(3),
  state VARCHAR(24) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE if_live_outbox (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id INTEGER NOT NULL REFERENCES live_flights(id),
  revision INTEGER NOT NULL,
  state VARCHAR(24) NOT NULL DEFAULT 'queued',
  action VARCHAR(16) NOT NULL DEFAULT 'sync',
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until TIMESTAMPTZ(3),
  error VARCHAR(500),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT if_live_outbox_revision UNIQUE (flight_id, revision)
);
CREATE INDEX if_live_outbox_ready ON if_live_outbox (state, next_attempt_at, lease_until);

INSERT INTO options (name, value) VALUES ('live_scheduling_mutex', '1');
COMMIT;
